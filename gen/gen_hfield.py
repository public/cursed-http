#!/usr/bin/env python3
"""Generate the two table blocks of include/hfield.h: the HPACK/QPACK Huffman tables (RFC 7541
Appendix B) and the nibble-class tables of the header checks. After scripts/fetch-thirdparty.sh nghttp2:
    python3 -I gen/gen_hfield.py           writes build/gen/hh_tables.h and build/gen/hv_tables.h
    python3 -I gen/gen_hfield.py --check   compares every generated table with include/hfield.h's (make hfield-check)
The code table is read from nghttp2's huff_sym_table (left-aligned 32-bit codes); the tables are
checked in (formatted by clang-format), so the fetch is only needed to regenerate or check."""

import re
import os
import sys

here = os.path.dirname(os.path.abspath(__file__)) + "/.."
src = open(here + "/third_party/nghttp2/lib/nghttp2_hd_huffman_data.c").read()
body = src[src.index("huff_sym_table[] = {") :]
body = body[: body.index("};")]
pairs = [(int(a), int(b, 16)) for a, b in re.findall(r"\{(\d+),\s*0x([0-9A-Fa-f]+)U\}", body)]
assert len(pairs) == 257, len(pairs)
LEN = [p[0] for p in pairs]
CODE = [p[1] >> (32 - p[0]) for p in pairs]  # right-aligned
assert all(5 <= l <= 30 for l in LEN) and LEN[256] == 30 and CODE[256] == (1 << 30) - 1

# canonical check: codes of each length are consecutive, and sorted by (len, code) the
# left-aligned codes increase, so per-length limits decode long codes.
order = sorted(range(257), key=lambda s: (LEN[s], CODE[s]))
for a, b in zip(order, order[1:]):
    la, lb = LEN[a], LEN[b]
    assert (CODE[a] + 1) << (lb - la) == CODE[b], (a, b)


def entry(idx, K):
    """Greedy multi-symbol decode of the K-bit window idx. Returns (syms, consumed, long)."""
    syms, used = [], 0
    while True:
        rem = K - used
        hit = None
        for s in range(256):  # EOS (256) is never emitted by the table
            l = LEN[s]
            if l <= rem and (idx >> (rem - l)) & ((1 << l) - 1) == CODE[s]:
                hit = s
                break
        if hit is None:
            break
        syms.append(hit)
        used += LEN[hit]
        if len(syms) == 2:
            break
    return syms, used, (used == 0)


out = []
w = out.append
w(
    "/* Generated by gen/gen_hfield.py from the RFC 7541 Appendix B code (as in nghttp2's"
    " huff_sym_table). Do not edit. */"
)
w("#ifndef HH_TABLES_H\n#define HH_TABLES_H\n#include <stdint.h>")
w("static const uint8_t hh_len[257] = {" + ",".join(map(str, LEN)) + "};")
# encoder: code left-aligned in 32 bits (the length is hh_len)
w("static const uint32_t hh_code_la[257] = {" + ",".join("0x%xu" % (c << (32 - l)) for c, l in zip(CODE, LEN)) + "};")
# long-code decode: per length L (1..30), lim[L] = first left-aligned (32-bit) code value of
# length > L, i.e. peek32 < lim[L] <=> code length <= L.  base[L]: index into hh_sorted of the
# first code of length L minus that code's value.
lim = [0] * 31
base = [0] * 31
first = {}
for i, s in enumerate(order):
    first.setdefault(LEN[s], (i, CODE[s]))
for L in range(1, 31):
    longer = [s for s in order if LEN[s] > L]
    lim[L] = (CODE[longer[0]] << (32 - LEN[longer[0]])) if longer else 1 << 32
    if L in first:
        i, c = first[L]
        base[L] = i - c
w("static const uint64_t hh_lim[31] = {" + ",".join("0x%xull" % x for x in lim) + "};")
w("static const int32_t hh_base[31] = {" + ",".join(map(str, base)) + "};")
w("static const uint16_t hh_sorted[257] = {" + ",".join(map(str, order)) + "};")
# the header checks' byte classes (hfield.h's hv__value_ok and hv__name_ok), so the decoder can
# report whether any decoded byte would fail them
tok = set(b"!#$%&'*+-.^_`|~0123456789abcdefghijklmnopqrstuvwxyz")


def value_ok(b):
    return (b >= 0x20 and b != 0x7F) or b == 9


for K in (12,):  # HH_K in hfield.h
    vals = []
    for idx in range(1 << K):
        syms, used, lng = entry(idx, K)
        s0 = syms[0] if syms else 0
        s1 = syms[1] if len(syms) > 1 else 0
        vbad = any(not value_ok(s) for s in syms)
        nbad = any(s not in tok for s in syms)
        vals.append(s0 | s1 << 8 | used << 16 | len(syms) << 24 | vbad << 26 | nbad << 27 | (0x80 << 24 if lng else 0))
    w(
        "/* K=%d window: bits 0-15 sym0|sym1<<8, 16-23 bits consumed, 24-25 nsyms, 26 a symbol fails"
        " hv__value_ok, 27 one fails hv__name_ok, 31 long code */" % K
    )
    w("static const uint32_t hh_dec%d[%d] = {" % (K, 1 << K))
    for i in range(0, len(vals), 8):
        w("  " + ",".join("0x%08xu" % v for v in vals[i : i + 8]) + ",")
    w("};")
w("#endif")
hh_out = "\n".join(out) + "\n"


# ---- header validation: nibble-class tables (lo[b & 15] & hi[b >> 4]) != 0 <=> b in set ----
def nib(name, ok):
    rows = {}
    for h in range(16):
        m = sum(1 << l for l in range(16) if ok(h * 16 + l))
        if m:
            rows.setdefault(m, []).append(h)
    assert len(rows) <= 8, (name, len(rows))
    lo = [0] * 16
    hi = [0] * 16
    for bit, (m, hs) in enumerate(rows.items()):
        for h in hs:
            hi[h] |= 1 << bit
        for l in range(16):
            if m >> l & 1:
                lo[l] |= 1 << bit
    for b in range(256):
        assert bool(lo[b & 15] & hi[b >> 4]) == bool(ok(b)), (name, b)
    return lo, hi


path = set(range(0x21, 0x7F)) | set(range(0x80, 0x100))
auth = set(b"!$%&'()*+,-.0123456789:;=@ABCDEFGHIJKLMNOPQRSTUVWXYZ[]_abcdefghijklmnopqrstuvwxyz~")
o = [
    "/* Generated by gen/gen_hfield.py. Do not edit. */",
    "#ifndef HV_TABLES_H",
    "#define HV_TABLES_H",
    "#include <stdint.h>",
]
for name, s in (("name", tok), ("auth", auth)):
    lo, hi = nib(name, lambda b, s=s: b in s)
    o.append("static const uint8_t hv_%s_lo[16] = {%s};" % (name, ",".join(map(str, lo))))
    o.append("static const uint8_t hv_%s_hi[16] = {%s};" % (name, ",".join(map(str, hi))))
o.append("#endif")
hv_out = "\n".join(o) + "\n"


def tables(text):  # name -> the numbers of every "static const T name[...] = {...};" in text
    return {
        m.group(1): [int(x.rstrip("uUlL"), 0) for x in re.findall(r"[0-9a-fA-Fx]+[uUlL]*", m.group(2))]
        for m in re.finditer(r"static const \w+ (\w+)\[\d*\] = \{([^}]*)\};", text)
    }


if sys.argv[1:] == ["--check"]:
    got, have = tables(hh_out + hv_out), tables(open(here + "/include/hfield.h").read())
    bad = [n for n in got if got[n] != have.get(n)] + [n for n in have if n not in got]
    print("hfield.h tables: " + ("MISMATCH " + " ".join(bad) if bad else "%d match the generator" % len(got)))
    sys.exit(1 if bad else 0)
os.makedirs(here + "/build/gen", exist_ok=True)
open(here + "/build/gen/hh_tables.h", "w").write(hh_out)
open(here + "/build/gen/hv_tables.h", "w").write(hv_out)
print("ok")
