#!/usr/bin/env python3
"""Extract RFC 9001 Appendix A (A.2 client Initial, A.3 server Initial, A.5 ChaCha20 short header)
into tests/rfc9001_vectors.h.
    curl -fsSL -o build/rfc9001.txt https://www.rfc-editor.org/rfc/rfc9001.txt
    python3 -I gen/gen_rfc9001.py build/rfc9001.txt > tests/rfc9001_vectors.h"""
import re, sys
lines = [l.rstrip("\n\f") for l in open(sys.argv[1], encoding="utf-8")]
lines = [l for l in lines if not re.match(r"^(Thomson & Turner|RFC 9001 )", l)]
HEX = re.compile(r"^\s+([0-9a-f]{2,}(\s+[0-9a-f]{2,})*)\s*$")
def block_after(marker, start=0):
    i = next(k for k in range(start, len(lines)) if marker in lines[k])
    out, k = "", i + 1
    while k < len(lines) and (not lines[k].strip() or HEX.match(lines[k])):
        if lines[k].strip(): out += lines[k].replace(" ", "")
        elif out and k + 1 < len(lines) and lines[k + 1].strip() and not HEX.match(lines[k + 1]): break
        k += 1
    return out, k
a2 = next(i for i, l in enumerate(lines) if l.startswith("A.2.  Client Initial"))
a3 = next(i for i, l in enumerate(lines) if l.startswith("A.3.  Server Initial"))
a5 = next(i for i, l in enumerate(lines) if l.startswith("A.5.  ChaCha20"))
crypto, _ = block_after("1162-byte payload:", a2)
client_pkt, _ = block_after("The resulting protected packet is:", a2)
server_payload, _ = block_after("no PADDING frames:", a3)
server_pkt, _ = block_after("The final protected packet is then:", a3)
def val(name, start):
    i = next(k for k in range(start, len(lines)) if re.match(r"^\s+%s\s+=" % re.escape(name), lines[k]))
    v = lines[i].split("=", 1)[1].strip().replace(" ", "")
    k = i + 1
    while HEX.match(lines[k]) and "=" not in lines[k]: v += lines[k].strip(); k += 1
    return v
secret = val("secret", a5) if any(re.match(r"^\s+secret\s+=", l) for l in lines[a5:a5 + 20]) else None
if secret is None:  # "secret" is on its own line, value on the next
    i = next(k for k in range(a5, len(lines)) if lines[k].strip() == "secret")
    secret = lines[i + 1].split("=", 1)[1].strip() + lines[i + 2].strip()
chacha_pkt = next(l for l in lines[a5:] if re.match(r"^\s+packet = ", l)).split("=", 1)[1].strip()
assert len(bytes.fromhex(client_pkt)) == 1200, len(client_pkt) // 2
assert len(bytes.fromhex(crypto)) == 245, len(crypto) // 2
assert len(bytes.fromhex(chacha_pkt)) == 21
def c(name, h): print("static const char %s[] = \"%s\"; /* %d bytes */" % (name, h, len(h) // 2))
print("/* Generated by gen/gen_rfc9001.py from RFC 9001 Appendix A. Do not edit. */")
c("rfc9001_client_dcid", "8394c8f03e515708")
c("rfc9001_a2_crypto", crypto)
c("rfc9001_a2_packet", client_pkt)
c("rfc9001_a3_payload", server_payload)
c("rfc9001_a3_packet", server_pkt)
c("rfc9001_a5_secret", secret.replace(" ", ""))
c("rfc9001_a5_packet", chacha_pkt)
