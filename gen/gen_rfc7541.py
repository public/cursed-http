#!/usr/bin/env python3
"""Extract RFC 7541 Appendix C (C.3-C.6) into tests/rfc7541_vectors.h: for each example, the encoded
block, the decoded header list and the dynamic table size after decoding.
    curl -fsSL -o build/rfc7541.txt https://www.rfc-editor.org/rfc/rfc7541.txt
    python3 -I gen/gen_rfc7541.py build/rfc7541.txt > tests/rfc7541_vectors.h"""
import re, sys
lines = [l.rstrip("\n\f") for l in open(sys.argv[1], encoding="utf-8")]
lines = [l for l in lines if not re.match(r"^(Peon & Ruellan|RFC 7541 )", l) and "\f" not in l]
out = []
i = 0
while i < len(lines):
    m = re.match(r"^C\.([3-6])\.([1-3])\.  ", lines[i])
    if not m:
        i += 1; continue
    grp, num = int(m.group(1)), int(m.group(2))
    j = i + 1
    while not lines[j].strip().startswith("Header list to encode:"): j += 1
    j += 1
    hdrs = []
    while not lines[j].strip().startswith("Hex dump of encoded data:"):
        t = lines[j].strip()
        if t:
            k = t.index(":", 1)  # pseudo names start with ':'
            hdrs.append((t[:k], t[k + 2:] if len(t) > k + 1 else ""))
        j += 1
    j += 1
    hexs = ""
    while not lines[j].strip().startswith("Decoding process:"):
        t = lines[j].split("|")[0].strip()
        hexs += t.replace(" ", "")
        j += 1
    while not re.match(r"^\s+Table size:", lines[j]) and not re.match(r"^\s+\(s = ", lines[j]) or "Table size" not in lines[j]:
        j += 1
    size = int(lines[j].split(":")[1])
    out.append((grp, num, bytes.fromhex(hexs), hdrs, size))
    i = j
assert len(out) == 12, len(out)
def cstr(b): return '"' + "".join("\\x%02x" % c for c in b) + '"'
print("/* Generated by gen/gen_rfc7541.py from RFC 7541 Appendix C.3-C.6. Do not edit. */")
print("typedef struct { int group, seq; const char *block; int blen; int n; const char *h[2 * 12]; int table_size; } rfc7541_case;")
print("static const rfc7541_case rfc7541_cases[] = {")
for g, n, blk, hdrs, size in out:
    hs = ", ".join(cstr(x.encode()) for kv in hdrs for x in kv)
    print("  {%d, %d, %s, %d, %d, {%s}, %d}," % (g, n, cstr(blk), len(blk), len(hdrs), hs, size))
print("};")
